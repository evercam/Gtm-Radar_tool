/**
 * Emits the SQL phase mapping from src/lib/phase.ts.
 *
 * Phase normalisation has to exist in two places: TypeScript, because the export
 * and the scoring pass read it row by row, and Postgres, because `search_projects`
 * needs to FILTER on it — and filtering in TypeScript meant fetching the top two
 * thousand rows by score and folding them, which silently missed every lower-scoring
 * project in the phase asked for.
 *
 * Two places, one source. The mapping is 117 raw values wide and changes whenever a
 * feed invents a new spelling; transcribing it into SQL by hand would produce a copy
 * that agrees today and diverges at the first edit, and the divergence would be
 * invisible — a filter quietly returning a slightly different set than the column
 * next to it. So the SQL is derived, and the derivation is this file.
 *
 *   node --experimental-transform-types --no-warnings \
 *        --import ./scripts/lib/register-alias.mjs scripts/generate-phase-sql.mjs
 *
 * Prints to stdout; redirect it into the migration. `scripts/test-phase-parity.mjs`
 * then checks the shipped function against the TypeScript on live data, so a
 * migration generated from a stale checkout cannot pass unnoticed.
 */

import { EXACT, RULES } from '@/lib/phase';

/** Single-quote a SQL string literal. */
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * A JavaScript regex source as a Postgres ARE pattern.
 *
 * Mostly identical, with one trap that would have been silent: `\b` is a WORD
 * BOUNDARY in JavaScript and a BACKSPACE CHARACTER in Postgres. `\bai\b` — the rule
 * that catches planning_ie's "AI" steps without matching every word containing
 * "ai" — would compile in Postgres, match nothing, and quietly reclassify those
 * rows. Postgres spells the word boundary `\y`.
 */
function toPostgresRegex(re) {
  const src = re.source;
  const unsupported = src.match(/\\[dswDSW]|\(\?[=!<]/);
  if (unsupported) {
    throw new Error(
      `Pattern ${re} uses ${unsupported[0]}, which this generator does not translate. ` +
        `Add a case here rather than hand-editing the SQL.`
    );
  }
  if (re.flags.replace('i', '')) {
    throw new Error(`Pattern ${re} carries flags this generator does not model: ${re.flags}`);
  }
  return src.replace(/\\b/g, '\\y');
}

const exactWhens = Object.entries(EXACT)
  .map(([raw, phase]) => `    WHEN ${lit(raw)} THEN ${lit(phase)}`)
  .join('\n');

const ruleWhens = RULES.map(
  ({ pattern, phase }) => `  IF k ~ ${lit(toPostgresRegex(pattern))} THEN RETURN ${lit(phase)}; END IF;`
).join('\n');

process.stdout.write(`-- GENERATED by scripts/generate-phase-sql.mjs from src/lib/phase.ts.
-- Do not edit by hand: re-run the generator and replace this file wholesale.
-- ${Object.keys(EXACT).length} exact mappings, ${RULES.length} ordered fallback rules.

/*
  The same normalisation lib/phase.ts performs, so a phase filter can be a WHERE
  clause against an index instead of a two-thousand-row scan folded in TypeScript.

  IMMUTABLE is required rather than decorative: the generated column below cannot
  exist without it. It is honestly immutable — the mapping is baked into the body,
  so the only way it changes is a migration that rewrites this function.

  The exact CASE returns early, before the rules run, and the rules stay in
  DECLARATION ORDER. Both matter: /^shelved/ has to win before the generic
  application pattern would claim it, exactly as in TypeScript.
*/
CREATE OR REPLACE FUNCTION normalise_phase(raw text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
AS $$
DECLARE
  k text;
  hit text;
BEGIN
  IF raw IS NULL OR btrim(raw) = '' THEN
    RETURN NULL;
  END IF;

  k := lower(regexp_replace(btrim(raw), '\\s+', ' ', 'g'));

  hit := CASE k
${exactWhens}
    ELSE NULL
  END;
  IF hit IS NOT NULL THEN
    RETURN hit;
  END IF;

  -- Fallback patterns, in declaration order. First match wins, as in TypeScript.
${ruleWhens}

  -- Unmapped stays NULL and visible, rather than guessed into the nearest bucket.
  RETURN NULL;
END;
$$;
`);
